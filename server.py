async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text(
        "Бот запущен. Перешлите сюда сообщение из группы или канала."
    )


async def handle_forwarded(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    msg = update.effective_message

    # 1) Это должна быть пересылка
    if not msg.forward_origin:
        return

    # Если это альбом (несколько фото/видео одним постом), Telegram присылает
    # каждый элемент отдельным апдейтом — отвечаем только на первый из них
    if msg.media_group_id:
        if msg.media_group_id in _processed_media_groups:
            return
        _processed_media_groups.add(msg.media_group_id)
        # не даём множеству расти бесконечно
        if len(_processed_media_groups) > 1000:
            _processed_media_groups.clear()

    # 2) Если пересылку сделал не Ваня — отдельная короткая реакция
    if update.effective_user.id != ALLOWED_USER_ID:
        await msg.reply_text("ИванАНТИБАЗА")
        return

    chat_id = msg.chat_id

    # "Печатает..." для комедийного эффекта перед ответом
    await context.bot.send_chat_action(chat_id=chat_id, action=ChatAction.TYPING)
    await asyncio.sleep(random.uniform(1.2, 2.8))

    text = msg.text or msg.caption or ""

    # Приоритет: ключевые слова -> тип контента (только если подпись короткая,
    # иначе это новость с картинкой, а не "просто фото") -> общий набор
    pool = detect_keyword_pool(text)
    if pool is None:
        if len(text.strip()) <= CONTENT_TEXT_THRESHOLD:
            content_type = detect_content_type(msg)
            pool = CONTENT_RESPONSES.get(content_type, RESPONSES)
        else:
            pool = RESPONSES

    reply = pick_response(pool, chat_id)

    # Счётчик пересылок за месяц (показываем не всегда, чтобы не приедалось)
    count = increment_counter(update.effective_user.id)
    if random.random() < 0.5:
        reply = f"{reply}\n\n(Это уже {count}-й перл за этот месяц 🏆)"

    # Фирменная подпись в конце каждого ответа
    reply = f"{reply}\n\n{SIGNATURE}"

    await msg.reply_text(reply)


def main():
    TOKEN = os.environ["BOT_TOKEN"]
    app = Application.builder().token(TOKEN).build()

    app.add_handler(CommandHandler("start", start))
    app.add_handler(
        MessageHandler(filters.FORWARDED, handle_forwarded)
    )

    app.run_polling()


if __name__ == "__main__":
    main()
