_last_response: dict[int, str] = {}

# Чтобы не отвечать на каждое фото/видео из одного альбома отдельно —
# запоминаем уже обработанные media_group_id (альбомы приходят как несколько сообщений)
_processed_media_groups: set[str] = set()

# Если один и тот же человек пересылает несколько сообщений подряд одним постом
# (например текст + отдельное видео), отвечаем только на первое в течение окна
_last_reply_time: dict[int, float] = {}
REPLY_COOLDOWN_SECONDS = 4


def pick_response(pool: list[str], chat_id: int) -> str:
    """Выбирает случайный ответ из pool, избегая повтора последнего в этом чате."""
    if len(pool) == 1:
        chosen = pool[0]
    else:
        chosen = random.choice(pool)
        while chosen == _last_response.get(chat_id):
            chosen = random.choice(pool)
    _last_response[chat_id] = chosen
    return chosen


# ---------------------------------------------------------------------------
# СЧЁТЧИК ПЕРЕСЫЛОК (сохраняется в JSON-файле, считает по месяцам)
# ---------------------------------------------------------------------------

def _load_counts() -> dict:
    if os.path.exists(COUNTER_FILE):
        try:
            with open(COUNTER_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, OSError):
            return {}
    return {}


def _save_counts(data: dict) -> None:
    with open(COUNTER_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def increment_counter(user_id: int) -> int:
    """Увеличивает счётчик пересылок для пользователя в текущем месяце и возвращает новое значение."""
    data = _load_counts()
    month_key = datetime.now().strftime("%Y-%m")
    user_key = str(user_id)
    data.setdefault(user_key, {})
    data[user_key][month_key] = data[user_key].get(month_key, 0) + 1
    _save_counts(data)
    return data[user_key][month_key]


