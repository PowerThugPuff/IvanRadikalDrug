LINK_RE = re.compile(r"https?://\S+")

# Если у фото/видео/голосового подпись длиннее этого числа символов — считаем,
# что это пересланная новость с картинкой, а не "просто фото" от Вани.
CONTENT_TEXT_THRESHOLD = 20

# Фирменная подпись, добавляется в конец каждого ответа бота
SIGNATURE = "IVAN=BAZA"


def detect_content_type(msg) -> str | None:
    if msg.photo:
        return "photo"
    if msg.video:
        return "video"
    if msg.voice or msg.audio:
        return "voice"
    text = msg.text or msg.caption or ""
    if LINK_RE.search(text):
        return "link"
    return None


def detect_keyword_pool(text: str) -> list[str] | None:
    text_lower = text.lower()
    for keyword, pool in KEYWORD_RESPONSES.items():
        if keyword in text_lower:
            return pool
    return None


